# Entrada das horas
horas = int(input("Digite as horas:"))

# Entrada dos minutos
minutos = int(input("Digite os minutos"))

# Converter horas para minutos e somar com os minutos
total = horas * 60 + minutos

# Resultado
print (f"{horas} horas e {minutos} minutos, são iguais a {total} minutos")