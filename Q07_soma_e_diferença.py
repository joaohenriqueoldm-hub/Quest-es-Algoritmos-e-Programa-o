# Entrada digitar os três numeros que serão utilizados
numero_1 = float(input("Digite o primeiro número:"))
numero_2 = float(input("Agora o segundo número:"))
numero_3 = float(input("Agora o terceiro número:"))

# Calculando a soma dos dois primeiros números
soma = numero_1 + numero_2

# Calculando a diferença entre os dois últimos números
diferenca = numero_2 - numero_3

# Resultado
print(f"A soma dos números {numero_1} e {numero_2} é: {soma} e a diferença entre {numero_2} e {numero_3} é: {diferenca}")

