# Entrada - inseir a base e a altura do triângulo
base = float(input("Digite o comprimento da base do triângulo:"))
altura = float(input("Digite o comprimento da altura do triângulo:"))

# Calcular a área do triângulo
base_vezes_altura = base * altura
area = base_vezes_altura / 2

# Exibir o resultado
print(f"A área do triângulo é igual a {area:.2f}")


